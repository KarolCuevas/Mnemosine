import { test, expect } from '@playwright/test'

test('subida real importa etiquetas y portada en detalle, biblioteca y reproductor', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_MEDIA_FIXTURE, 'Ejecutar con python -m scripts.e2e para usar audio y almacenamiento temporales.')
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/acceso')
  await page.getByLabel('Usuario o correo').fill(process.env.E2E_IDENTITY)
  await page.getByLabel('Contraseña').fill(process.env.E2E_PASSWORD)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/biblioteca$/)
  await page.getByRole('main').getByRole('link', { name: 'Subir música', exact: true }).click()
  await page.getByLabel('Archivo de audio').setInputFiles(process.env.E2E_MEDIA_FIXTURE)
  await expect(page.getByLabel('Título', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Artista', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'Guardar como privada' }).click()
  const result = page.getByRole('status')
  await expect(result).toContainText('“Aurora etiquetada” subida correctamente.')
  await expect(result).toContainText('Álvaro de prueba, Invitada · Horizontes sintéticos')
  await expect(result).toBeFocused()
  const expectCover = async locator => {
    await expect(locator).toHaveAttribute('src', /\/api\/tracks\/\d+\/cover$/)
    await expect.poll(() => locator.evaluate(image => image.complete && image.naturalWidth > 0)).toBe(true)
  }
  await expectCover(result.locator('img'))
  await page.screenshot({ path: testInfo.outputPath('subida-con-portada.png'), fullPage: true })
  await page.setViewportSize({ width: 320, height: 740 })
  const expectContained = async () => {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.querySelector('main').scrollWidth <= document.querySelector('main').clientWidth)).toBe(true)
  }
  await expectContained()
  await result.scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('subida-con-portada-mobile.png'), fullPage: true })
  await result.getByRole('link', { name: 'Ver detalle' }).click()
  await expect(page.getByRole('heading', { name: 'Aurora etiquetada', exact: true })).toBeVisible()
  await expectCover(page.locator('.song-hero img'))
  const tags = page.getByRole('definition').filter({ hasText: 'Ambient' })
  await expect(tags).toBeVisible()
  await expect(page.getByText('Ensamble de prueba', { exact: true })).toBeVisible()
  await expectContained()
  await page.getByRole('link', { name: 'Tu biblioteca', exact: true }).click()
  await expectCover(page.locator('.track-item img').first())
  await page.getByRole('button', { name: 'Vista de cuadrícula' }).click()
  await expectCover(page.locator('.track-grid img').first())
  await page.getByRole('button', { name: 'Reproducir Aurora etiquetada', exact: true }).click()
  const player = page.getByRole('region', { name: 'Reproductor de música' })
  await expectCover(player.locator('img'))
  await expect(player.locator('img')).toBeVisible()
  await expect(player.getByRole('button', { name: 'Pausar', exact: true })).toBeVisible()
  await player.getByRole('button', { name: 'Pausar', exact: true }).click()
  await expectContained()
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.screenshot({ path: testInfo.outputPath('biblioteca-con-portada.png') })
  expect(errors).toEqual([])
})
